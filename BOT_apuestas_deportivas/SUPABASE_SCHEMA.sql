-- 1) Usuarios del bot
create table if not exists public.users (
    id                  bigint generated by default as identity primary key,
    identificacion      text unique not null,
    usuario             text unique not null,
    clave               text not null,
    correo              text,
    fecha_nacimiento    text,
    fecha_inicio        text,
    fecha_final         text,
    perfil              text default 'usuario',
    numero_ingresos     integer default 0,
    analisis_realizados integer default 0,
    estado              text default 'pendiente',   -- pendiente | aprobado | rechazado
    membresia           text default 'gratis'       -- gratis | paga
);

-- 2) Registro de picks del bot (rendimiento + ROI + Brier + CLV)
create table if not exists public.picks (
    id           bigint generated by default as identity primary key,
    ts           timestamptz default now(),
    evento_id    text,
    sport_key    text,
    deporte      text,
    evento       text,
    empieza      text,
    mercado      text,
    market_key   text,
    seleccion    text,
    seleccion_raw text,
    linea        double precision,
    cuota        double precision,
    casa         text,
    prob_modelo  double precision,
    edge         double precision,
    kelly_frac   double precision,
    riesgo       text,
    origen       text default 'ia',
    usuario      text,
    resultado    text default 'pendiente',   -- pendiente | ganada | perdida | void
    closing_odds double precision,
    clv          double precision
);
create index if not exists picks_evento_id_idx   on public.picks (evento_id);
create index if not exists picks_resultado_idx   on public.picks (resultado);
create index if not exists picks_ts_idx          on public.picks (ts);

-- 3) Historial de ingresos (SOLO visible para el ADMINISTRADOR MASTER)
create table if not exists public.login_history (
    id             bigint generated by default as identity primary key,
    ts             timestamptz default now(),
    usuario        text,
    identificacion text,
    es_master      boolean default false,
    evento         text default 'login',   -- login | crud | extender | crear | borrar | reset_clave
    detalle        text
);
create index if not exists login_history_ts_idx      on public.login_history (ts);
create index if not exists login_history_usuario_idx on public.login_history (usuario);

-- 4) Seguridad: RLS activado. Con service_role el servidor accede igual.
--    Nadie con anon key podrá leer/escribir nada.
alter table public.users         enable row level security;
alter table public.picks         enable row level security;
alter table public.login_history enable row level security;

-- (Sin políticas = sólo service_role, que bypasea RLS. Perfecto para backend Streamlit.)

-- 5) Verificación rápida: deberías ver las 3 tablas con 0 filas
select table_name from information_schema.tables
where table_schema = 'public' and table_name in ('users', 'picks', 'login_history');
